#!/usr/bin/env python3
"""Build the full reconciliation matrix from scenario tags and editorial decisions."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reason-commons-spec"))
from check_bundle import feature_paths, parse_scenarios  # noqa: E402


def render_matrix(scenarios, decisions):
    rows = ["<!-- Generated by scripts/build_reconciliation.py; edit features and reconciliation-decisions.json. -->",
            "", "## Every scenario", "",
            "The entry point links to the owning feature, whose steps define the observable",
            "application or interface operation. Automated evidence is the declared runner",
            "and the complete v1 gate; semantic and participant evidence remains outstanding.", "",
            "| ID | Observable behavior / entry point | Increment · release · mode | Verification | Disposition and reason |",
            "|---|---|---|---|---|"]
    for s in sorted(scenarios, key=lambda s: int(s["id"][1:])):
        d = decisions[s["id"]]
        evidence = ("complete v1 gate" if s["mode"] == "automated" else "evaluation outstanding") if s["release"] == "v1" else "future contract; not delivered"
        previous = f" Previously {d['previous']['phase']} / {d['previous']['release']}." if d["previous"] else ""
        cells = [s["id"], f"[{s['name']}](../{s['source']}) ({s['cases']} cases)",
                 f"{s['phase']} · {s['release']} · {s['mode']}", evidence,
                 d["disposition"] + ". " + d["reason"] + previous]
        rows.append("| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    return "\n".join(rows) + "\n"


def main():
    spec = ROOT / "reason-commons-spec"
    manifest = json.loads((spec / "delivery-phases.json").read_text())
    scenarios = [s for path in feature_paths(manifest)
                 for s in parse_scenarios(path.read_text(), path.resolve().relative_to(ROOT).as_posix())[0]]
    decisions = json.loads((spec / "reconciliation-decisions.json").read_text())["scenarios"]
    by_id = {d["id"]: d for d in decisions}
    if len(by_id) != len(decisions) or set(by_id) != {s["id"] for s in scenarios}:
        raise SystemExit("Reconciliation decisions must cover each identity exactly once")
    path = ROOT / "docs/v1-reconciliation.md"
    intro = path.read_text().split("<!-- Generated by", 1)[0].rstrip()
    path.write_text(intro + "\n\n" + render_matrix(scenarios, by_id))
    print(f"Reconciled {len(scenarios)} identities in {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
